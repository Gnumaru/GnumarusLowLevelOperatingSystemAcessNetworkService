func param(name, location string, required bool, typ, desc string, rest ...any) map[string]any {
	p := map[string]any{
		"name": name, "location": location,
		"required": mustEnc(required), "type": typ, "description": desc,
	}
	// rest[0] = *string default, rest[1] = []string allowed.
	if len(rest) > 0 {
		if def, ok := rest[0].(*string); ok && def != nil {
			p["default"] = *def
		}
	}
	if len(rest) > 1 {
		if allowed, ok := rest[1].([]string); ok && allowed != nil {
			arr := make([]any, len(allowed))
			for i, v := range allowed {
				arr[i] = v
			}
			p["allowed"] = arr
		}
	}
	return p
}

func strptr(s string) *string { return &s }

func route(method, url, name, desc string, params []any, response string, errors ...string) map[string]any {
	r := map[string]any{
		"method": method, "url": url, "name": name,
		"description": desc, "params": params, "response": response,
	}
	if len(errors) > 0 {
		r["errors"] = errors[0]
	}
	return r
}

